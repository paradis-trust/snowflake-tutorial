-- Persisted result cache: this pair has a query text not used above. The first
-- statement executes; the byte-for-byte identical second statement should be
-- returned from persisted results when Snowflake's reuse conditions are met.
ALTER SESSION SET USE_CACHED_RESULT = TRUE;

