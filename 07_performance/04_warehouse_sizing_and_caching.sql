SELECT 'WAREHOUSE_AND_CACHE', 'XS_WARM', LAST_QUERY_ID(),
       'X-Small second run; result reuse disabled, warehouse remains running';

-- Small: suspending before resizing removes the previous warehouse-cache state.
-- Compare cold with cold and warm with warm; do not compare XS_WARM to SMALL_COLD.
ALTER WAREHOUSE PERF_TEST_WH SUSPEND;
ALTER WAREHOUSE PERF_TEST_WH SET WAREHOUSE_SIZE = 'SMALL';
ALTER WAREHOUSE PERF_TEST_WH RESUME;

