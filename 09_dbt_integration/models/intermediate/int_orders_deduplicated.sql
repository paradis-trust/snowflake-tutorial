WITH STAGED_ORDERS AS (
  SELECT *
  FROM {{ ref('stg_orders') }}
),

DEDUPLICATED AS (
  SELECT *
  FROM STAGED_ORDERS
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY ORDER_ID
    ORDER BY BRONZE_LOADED_AT DESC
  ) = 1
),

DERIVED AS (
  SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    STATUS,
    SALES_CHANNEL,
    CURRENCY,
    ORDER_TOTAL,
    COALESCE(DISCOUNT_AMOUNT, 0) AS DISCOUNT_AMOUNT,
    ORDER_TOTAL - COALESCE(DISCOUNT_AMOUNT, 0) AS NET_ORDER_TOTAL,
    SHIPPING_CITY,
    SHIPPING_COUNTRY,
    STATUS IN ('DELIVERED', 'SHIPPED') AS IS_COMPLETED,
    BRONZE_LOADED_AT
  FROM DEDUPLICATED
)

SELECT *
FROM DERIVED
