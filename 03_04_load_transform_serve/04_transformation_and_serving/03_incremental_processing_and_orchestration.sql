-- Dynamic tables declare the result and a freshness target. Snowflake manages
-- the refresh work instead of requiring a stream/task implementation.
CREATE OR REPLACE DYNAMIC TABLE GOLD.DT_DAILY_SALES (
  ORDER_DATE,
  SHIPPING_COUNTRY,
  CURRENCY,
  ORDER_COUNT,
  GROSS_ORDER_TOTAL,
  NET_ORDER_TOTAL
)
  TARGET_LAG = '5 MINUTES'
  WAREHOUSE = COMPUTE_WH
  REFRESH_MODE = INCREMENTAL
AS
SELECT
  ORDER_DATE,
  SHIPPING_COUNTRY,
  CURRENCY,
  COUNT(*) AS ORDER_COUNT,
  SUM(ORDER_TOTAL) AS GROSS_ORDER_TOTAL,
  SUM(NET_ORDER_TOTAL) AS NET_ORDER_TOTAL
FROM SILVER.SILVER_ORDERS
WHERE IS_COMPLETED
GROUP BY ORDER_DATE, SHIPPING_COUNTRY, CURRENCY;

SHOW DYNAMIC TABLES IN SCHEMA GOLD;
SELECT * FROM GOLD.DT_DAILY_SALES ORDER BY ORDER_DATE, SHIPPING_COUNTRY, CURRENCY;
