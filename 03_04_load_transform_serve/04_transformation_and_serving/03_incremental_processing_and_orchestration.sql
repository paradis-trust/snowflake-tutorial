-- Module 4: Transformation and Serving
-- Process new bronze orders incrementally with a stream and task, then use a
-- dynamic table to maintain a gold aggregate.
-- Run 02_full_refresh_transformation_patterns.sql first.

USE DATABASE LOAD_TRANSFORM_SERVE;

-- An append-only stream tracks orders inserted after the stream is created.
-- It is appropriate for an ingestion feed that does not send source deletes.
CREATE OR REPLACE STREAM BRONZE.BRONZE_ORDERS_STREAM
  ON TABLE BRONZE.BRONZE_ORDERS
  APPEND_ONLY = TRUE;

-- MERGE is the incremental upsert pattern: matching order IDs are updated and
-- new order IDs are inserted. The stream is consumed only when this statement
-- executes successfully.
MERGE INTO SILVER.SILVER_ORDERS AS TARGET
USING (
  SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    UPPER(TRIM(STATUS)) AS STATUS,
    UPPER(TRIM(SALES_CHANNEL)) AS SALES_CHANNEL,
    CURRENCY,
    ORDER_TOTAL,
    DISCOUNT_AMOUNT,
    ORDER_TOTAL - DISCOUNT_AMOUNT AS NET_ORDER_TOTAL,
    INITCAP(TRIM(SHIPPING_CITY)) AS SHIPPING_CITY,
    SHIPPING_COUNTRY,
    STATUS IN ('DELIVERED', 'SHIPPED') AS IS_COMPLETED,
    LOADED_AT AS BRONZE_LOADED_AT,
    CURRENT_TIMESTAMP() AS TRANSFORMED_AT
  FROM BRONZE.BRONZE_ORDERS_STREAM
) AS SOURCE
ON TARGET.ORDER_ID = SOURCE.ORDER_ID
WHEN MATCHED THEN UPDATE SET
  CUSTOMER_ID = SOURCE.CUSTOMER_ID,
  ORDER_DATE = SOURCE.ORDER_DATE,
  STATUS = SOURCE.STATUS,
  SALES_CHANNEL = SOURCE.SALES_CHANNEL,
  CURRENCY = SOURCE.CURRENCY,
  ORDER_TOTAL = SOURCE.ORDER_TOTAL,
  DISCOUNT_AMOUNT = SOURCE.DISCOUNT_AMOUNT,
  NET_ORDER_TOTAL = SOURCE.NET_ORDER_TOTAL,
  SHIPPING_CITY = SOURCE.SHIPPING_CITY,
  SHIPPING_COUNTRY = SOURCE.SHIPPING_COUNTRY,
  IS_COMPLETED = SOURCE.IS_COMPLETED,
  BRONZE_LOADED_AT = SOURCE.BRONZE_LOADED_AT,
  TRANSFORMED_AT = SOURCE.TRANSFORMED_AT
WHEN NOT MATCHED THEN INSERT (
  ORDER_ID, CUSTOMER_ID, ORDER_DATE, STATUS, SALES_CHANNEL,
  CURRENCY, ORDER_TOTAL, DISCOUNT_AMOUNT, NET_ORDER_TOTAL,
  SHIPPING_CITY, SHIPPING_COUNTRY, IS_COMPLETED,
  BRONZE_LOADED_AT, TRANSFORMED_AT
) VALUES (
  SOURCE.ORDER_ID, SOURCE.CUSTOMER_ID, SOURCE.ORDER_DATE, SOURCE.STATUS,
  SOURCE.SALES_CHANNEL, SOURCE.CURRENCY, SOURCE.ORDER_TOTAL,
  SOURCE.DISCOUNT_AMOUNT, SOURCE.NET_ORDER_TOTAL, SOURCE.SHIPPING_CITY,
  SOURCE.SHIPPING_COUNTRY, SOURCE.IS_COMPLETED, SOURCE.BRONZE_LOADED_AT,
  SOURCE.TRANSFORMED_AT
);

-- The task automates the same MERGE for future stream changes.
CREATE OR REPLACE TASK SILVER.SILVER_ORDERS_INCREMENTAL_TASK
  WAREHOUSE = TUTO_WH
  SCHEDULE = '5 MINUTES'
  WHEN SYSTEM$STREAM_HAS_DATA('LOAD_TRANSFORM_SERVE.BRONZE.BRONZE_ORDERS_STREAM')
AS
MERGE INTO SILVER.SILVER_ORDERS AS TARGET
USING (
  SELECT
    ORDER_ID,
    CUSTOMER_ID,
    ORDER_DATE,
    UPPER(TRIM(STATUS)) AS STATUS,
    UPPER(TRIM(SALES_CHANNEL)) AS SALES_CHANNEL,
    CURRENCY,
    ORDER_TOTAL,
    DISCOUNT_AMOUNT,
    ORDER_TOTAL - DISCOUNT_AMOUNT AS NET_ORDER_TOTAL,
    INITCAP(TRIM(SHIPPING_CITY)) AS SHIPPING_CITY,
    SHIPPING_COUNTRY,
    STATUS IN ('DELIVERED', 'SHIPPED') AS IS_COMPLETED,
    LOADED_AT AS BRONZE_LOADED_AT,
    CURRENT_TIMESTAMP() AS TRANSFORMED_AT
  FROM BRONZE.BRONZE_ORDERS_STREAM
) AS SOURCE
ON TARGET.ORDER_ID = SOURCE.ORDER_ID
WHEN MATCHED THEN UPDATE SET
  CUSTOMER_ID = SOURCE.CUSTOMER_ID,
  ORDER_DATE = SOURCE.ORDER_DATE,
  STATUS = SOURCE.STATUS,
  SALES_CHANNEL = SOURCE.SALES_CHANNEL,
  CURRENCY = SOURCE.CURRENCY,
  ORDER_TOTAL = SOURCE.ORDER_TOTAL,
  DISCOUNT_AMOUNT = SOURCE.DISCOUNT_AMOUNT,
  NET_ORDER_TOTAL = SOURCE.NET_ORDER_TOTAL,
  SHIPPING_CITY = SOURCE.SHIPPING_CITY,
  SHIPPING_COUNTRY = SOURCE.SHIPPING_COUNTRY,
  IS_COMPLETED = SOURCE.IS_COMPLETED,
  BRONZE_LOADED_AT = SOURCE.BRONZE_LOADED_AT,
  TRANSFORMED_AT = SOURCE.TRANSFORMED_AT
WHEN NOT MATCHED THEN INSERT (
  ORDER_ID, CUSTOMER_ID, ORDER_DATE, STATUS, SALES_CHANNEL,
  CURRENCY, ORDER_TOTAL, DISCOUNT_AMOUNT, NET_ORDER_TOTAL,
  SHIPPING_CITY, SHIPPING_COUNTRY, IS_COMPLETED,
  BRONZE_LOADED_AT, TRANSFORMED_AT
) VALUES (
  SOURCE.ORDER_ID, SOURCE.CUSTOMER_ID, SOURCE.ORDER_DATE, SOURCE.STATUS,
  SOURCE.SALES_CHANNEL, SOURCE.CURRENCY, SOURCE.ORDER_TOTAL,
  SOURCE.DISCOUNT_AMOUNT, SOURCE.NET_ORDER_TOTAL, SOURCE.SHIPPING_CITY,
  SOURCE.SHIPPING_COUNTRY, SOURCE.IS_COMPLETED, SOURCE.BRONZE_LOADED_AT,
  SOURCE.TRANSFORMED_AT
);

